"""Generate and verify GNOME brand token files from vendored ux/brand/tokens.json (HARMONY 10.1)."""

from __future__ import annotations

import argparse
import ast
import hashlib
import io
import json
import re
import sys
import tokenize
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ACTIVE_STATUSES = frozenset({"decided", "placeholder"})
DEFERRED_STATUSES = frozenset({"proposed", "pending"})

HEX_TOKEN_RE = re.compile(r"^#[0-9A-F]{6}(?:[0-9A-F]{2})?$")
HEX_LITERAL_RE = re.compile(r"#[0-9a-fA-F]{3,8}\b")
COLOR_FUNC_RE = re.compile(r"\b(?:rgb|rgba|hsl|hsla)\s*\(", re.IGNORECASE)
ADW_PALETTE_RE = re.compile(
    r"(?:@|--)(?:blue|green|yellow|orange|red|purple|brown|light|dark)_[1-5]\b"
    r"|--(?:blue|green|yellow|orange|red|purple|brown|light|dark)-[1-5]\b"
)
PRE_W1_BEGIN = "BEGIN PRE-W1 LEGACY FALLBACKS"
PRE_W1_END = "END PRE-W1 LEGACY FALLBACKS"


def load_and_validate_vendored(root: Path = ROOT) -> tuple[str, dict[str, tuple[str, str]], dict[str, tuple[str, str]]]:
    upstream_path = root / "ux/brand/UPSTREAM.json"
    tokens_path = root / "ux/brand/tokens.json"
    if not upstream_path.is_file():
        raise ValueError(f"Missing upstream pin file: {upstream_path}")
    if not tokens_path.is_file():
        raise ValueError(f"Missing vendored token file: {tokens_path}")

    upstream = json.loads(upstream_path.read_text(encoding="utf-8"))
    if upstream.get("repository") != "codemyriad/cassini-ux":
        raise ValueError(f"Unexpected repository in {upstream_path}: {upstream.get('repository')!r}")
    commit = upstream.get("commit", "")
    if not isinstance(commit, str) or not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError(f"Invalid 40-hex commit in {upstream_path}: {commit!r}")

    sha_map = upstream.get("sha256") or {}
    if "tokens.json" not in sha_map:
        raise ValueError(f"Missing tokens.json SHA-256 entry in {upstream_path}")
    for rel_key, expected_sha in sha_map.items():
        asset_path = root / "ux/brand" / rel_key
        if not asset_path.is_file():
            raise ValueError(f"Missing vendored brand file: {asset_path}")
        asset_bytes = asset_path.read_bytes()
        actual_sha = hashlib.sha256(asset_bytes).hexdigest()
        if actual_sha != expected_sha:
            raise ValueError(f"SHA-256 mismatch for ux/brand/{rel_key}: expected {expected_sha}, got {actual_sha}")
        if rel_key.startswith("mark/"):
            src_copy = root / "src/brand" / rel_key
            if not src_copy.is_file() or src_copy.read_bytes() != asset_bytes:
                raise ValueError(f"src/brand/{rel_key} differs from vendored ux/brand/{rel_key}")

    raw_bytes = tokens_path.read_bytes()

    payload = json.loads(raw_bytes.decode("utf-8"))
    if payload.get("schema") != "cassini-ux/brand-tokens@1":
        raise ValueError(f"Unsupported token schema: {payload.get('schema')!r}")
    if payload.get("modes") != ["light", "dark"]:
        raise ValueError(f"Unsupported token modes: {payload.get('modes')!r}")

    def extract_section(section: dict[str, dict]) -> dict[str, tuple[str, str]]:
        out: dict[str, tuple[str, str]] = {}
        for name, spec in section.items():
            status = spec.get("status")
            if status not in ACTIVE_STATUSES | DEFERRED_STATUSES:
                raise ValueError(f"Unknown status {status!r} for token {name!r}")
            if status not in ACTIVE_STATUSES:
                continue
            light = str(spec["light"]).upper()
            dark = str(spec["dark"]).upper()
            for mode_name, val in (("light", light), ("dark", dark)):
                if not HEX_TOKEN_RE.fullmatch(val):
                    raise ValueError(f"Invalid {mode_name} hex {val!r} for token {name!r}")
            out[name] = (light, dark)
        return out

    tokens = extract_section(payload.get("tokens") or {})
    derived = extract_section(payload.get("derived") or {})
    if set(tokens) & set(derived):
        raise ValueError(f"Overlapping base and derived token names: {set(tokens) & set(derived)}")
    return commit, tokens, derived


def render_tokens_css(
    commit: str,
    tokens: dict[str, tuple[str, str]],
    derived: dict[str, tuple[str, str]],
) -> str:
    merged = list(tokens.items()) + list(derived.items())
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        f"/* DO NOT EDIT: generated by build-aux/generate-brand-tokens.py from codemyriad/cassini-ux@{commit}:brand/tokens.json */",
        "",
        ":root {",
    ]
    for name, (light, _dark) in merged:
        lines.append(f"  --cx-{name}: {light};")
    lines.extend(
        [
            "}",
            "",
            "@media (prefers-color-scheme: dark) {",
            "  :root {",
        ]
    )
    for name, (_light, dark) in merged:
        lines.append(f"    --cx-{name}: {dark};")
    lines.extend(["  }", "}", ""])
    return "\n".join(lines)


def render_brand_tokens_py(
    commit: str,
    tokens: dict[str, tuple[str, str]],
    derived: dict[str, tuple[str, str]],
) -> str:
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        f"# DO NOT EDIT: generated by build-aux/generate-brand-tokens.py from codemyriad/cassini-ux@{commit}:brand/tokens.json",
        '"""Generated brand colour tokens from ux/brand/tokens.json."""',
        "",
        f'UPSTREAM_COMMIT = "{commit}"',
        "",
        "TOKENS: dict[str, tuple[str, str]] = {",
    ]
    for name, (light, dark) in tokens.items():
        lines.append(f'    "{name}": ("{light}", "{dark}"),')
    lines.extend(
        [
            "}",
            "",
            "DERIVED_TOKENS: dict[str, tuple[str, str]] = {",
        ]
    )
    for name, (light, dark) in derived.items():
        lines.append(f'    "{name}": ("{light}", "{dark}"),')
    lines.extend(["}", ""])
    return "\n".join(lines)


def _docstring_lines(tree: ast.AST) -> set[int]:
    lines: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
            first = node.body[0]
            if (
                isinstance(first, ast.Expr)
                and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)
            ):
                for lineno in range(first.lineno, (first.end_lineno or first.lineno) + 1):
                    lines.add(lineno)
    return lines


def _pre_w1_fallback_lines(text: str) -> set[int]:
    allowed: set[int] = set()
    inside = False
    for lineno, line in enumerate(text.splitlines(), 1):
        if PRE_W1_BEGIN in line:
            if inside:
                raise ValueError(f"Nested {PRE_W1_BEGIN} at line {lineno}")
            inside = True
            continue
        if PRE_W1_END in line:
            if not inside:
                raise ValueError(f"Unmatched {PRE_W1_END} at line {lineno}")
            inside = False
            continue
        if inside:
            allowed.add(lineno)
    if inside:
        raise ValueError(f"Unclosed {PRE_W1_BEGIN}")
    return allowed


def _has_unapplied_w1_roles(root: Path) -> bool:
    tokens_py = root / "src/cassini_talk/tokens.py"
    if not tokens_py.is_file():
        return False
    src_dir = str(root / "src")
    added = False
    if src_dir not in sys.path:
        sys.path.insert(0, src_dir)
        added = True
    try:
        namespace: dict[str, object] = {"__package__": "cassini_talk"}
        brand_ns: dict[str, object] = {}
        exec((root / "src/cassini_talk/_brand_tokens.py").read_text(encoding="utf-8"), brand_ns)
        code = tokens_py.read_text(encoding="utf-8").replace(
            "from ._brand_tokens import DERIVED_TOKENS, TOKENS, UPSTREAM_COMMIT",
            "",
        )
        namespace.update(
            DERIVED_TOKENS=brand_ns["DERIVED_TOKENS"],
            TOKENS=brand_ns["TOKENS"],
            UPSTREAM_COMMIT=brand_ns["UPSTREAM_COMMIT"],
        )
        exec(code, namespace)
        return bool(namespace.get("UNAPPLIED_W1_ROLES"))
    finally:
        if added:
            sys.path.remove(src_dir)


def _find_literal_in_text(value: str) -> str | None:
    for regex in (HEX_LITERAL_RE, COLOR_FUNC_RE, ADW_PALETTE_RE):
        match = regex.search(value)
        if match:
            return match.group(0)
    return None


def scan_source_literals(root: Path = ROOT, *, allow_pre_w1: bool | None = None) -> list[str]:
    src_root = root / "src"
    generated = {
        src_root / "tokens.css",
        src_root / "cassini_talk/_brand_tokens.py",
    }
    pre_w1_files = {
        src_root / "style.css",
        src_root / "cassini_talk/tokens.py",
    }
    if allow_pre_w1 is None:
        allow_pre_w1 = _has_unapplied_w1_roles(root)

    violations: list[str] = []
    for path in sorted(src_root.rglob("*")):
        if not path.is_file() or path in generated:
            continue
        if path.suffix not in {".py", ".css", ".ui", ".xml", ".c", ".h"}:
            continue
        text = path.read_text(encoding="utf-8")
        rel = path.relative_to(root).as_posix()
        fallback_lines = _pre_w1_fallback_lines(text)
        if fallback_lines and (not allow_pre_w1 or path not in pre_w1_files):
            violations.append(
                f"{rel}: {PRE_W1_BEGIN} block is not permitted once UNAPPLIED_W1_ROLES is empty or outside style.css/tokens.py"
            )
            fallback_lines = set()

        if path.suffix == ".py":
            doc_lines = _docstring_lines(ast.parse(text, filename=rel))
            for tok in tokenize.generate_tokens(io.StringIO(text).readline):
                if tok.type != tokenize.STRING:
                    continue
                lineno = tok.start[0]
                if lineno in doc_lines or lineno in fallback_lines:
                    continue
                hit = _find_literal_in_text(tok.string)
                if hit:
                    violations.append(f"{rel}:{lineno}: colour literal {hit!r} outside generated token files")
        else:
            cleaned = re.sub(r"/\*.*?\*/|<!--.*?-->", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.DOTALL)
            for lineno, line in enumerate(cleaned.splitlines(), 1):
                if lineno in fallback_lines:
                    continue
                if path.suffix in {".c", ".h"} and "//" in line:
                    line = line.split("//", 1)[0]
                hit = _find_literal_in_text(line)
                if hit:
                    violations.append(f"{rel}:{lineno}: colour literal {hit!r} outside generated token files")
    return violations


def check_all(root: Path = ROOT) -> None:
    commit, tokens, derived = load_and_validate_vendored(root)
    expected_css = render_tokens_css(commit, tokens, derived)
    expected_py = render_brand_tokens_py(commit, tokens, derived)

    css_path = root / "src/tokens.css"
    py_path = root / "src/cassini_talk/_brand_tokens.py"
    if not css_path.is_file() or css_path.read_text(encoding="utf-8") != expected_css:
        raise ValueError(
            "src/tokens.css differs from ux/brand/tokens.json; run python3 build-aux/generate-brand-tokens.py"
        )
    if not py_path.is_file() or py_path.read_text(encoding="utf-8") != expected_py:
        raise ValueError(
            "src/cassini_talk/_brand_tokens.py differs from ux/brand/tokens.json; run python3 build-aux/generate-brand-tokens.py"
        )

    violations = scan_source_literals(root)
    if violations:
        raise ValueError("Colour literals found outside generated token files:\n  " + "\n  ".join(violations))


def write_all(root: Path = ROOT) -> None:
    commit, tokens, derived = load_and_validate_vendored(root)
    (root / "src/tokens.css").write_text(render_tokens_css(commit, tokens, derived), encoding="utf-8")
    (root / "src/cassini_talk/_brand_tokens.py").write_text(
        render_brand_tokens_py(commit, tokens, derived), encoding="utf-8"
    )
    check_all(root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files and scan src/ for colour literals")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        if args.check:
            check_all(args.root)
            print("Verified vendored brand/tokens.json, generated token files, and src/ literal scan.")
        else:
            write_all(args.root)
            print("Generated src/tokens.css and src/cassini_talk/_brand_tokens.py.")
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
