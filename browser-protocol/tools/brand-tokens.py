#!/usr/bin/env python3
"""Generate extension/brand-tokens.css from the vendored cassini-ux brand/tokens.json.

The popup reads every colour from this file (HARMONY 10.1 applied to the companion): one CSS
custom property per `decided` or `placeholder` role, `--cx-<name>`, with the light value on
:root and the dark value under prefers-color-scheme: dark. `proposed` and `pending` roles are
never emitted, nor the desktop-only reference roles in SKIP. Run with --write after bumping
ux/UPSTREAM.json; without it, exit 1 on drift.
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
SOURCE = root / 'ux' / 'brand' / 'tokens.json'
TARGET = root / 'extension' / 'brand-tokens.css'
READ = ('decided', 'placeholder')
# Desktop-only reference roles the shared, platform-neutral extension never draws.
SKIP = {'sidebar-mac'}


def css_colour(value):
    """#RRGGBB stays; #RRGGBBAA becomes rgb() with alpha so every browser reads it the same."""
    if len(value) == 9:
        r, g, b, a = (int(value[i:i + 2], 16) for i in (1, 3, 5, 7))
        return f'rgb({r} {g} {b} / {round(a / 255, 3)})'
    return value


def roles(tokens):
    out = {}
    for group in ('tokens', 'derived'):
        for name, role in tokens.get(group, {}).items():
            if role['status'] in READ and name not in SKIP:
                out[name] = {mode: role[mode] for mode in tokens['modes']}
    return out


def render(tokens):
    table = roles(tokens)
    width = max(len(name) for name in table)
    def block(mode, indent):
        return ''.join(f'{indent}--cx-{name}:{" " * (width - len(name))} {css_colour(values[mode])};\n'
                       for name, values in table.items())
    return ('/* Generated by tools/brand-tokens.py from ux/brand/tokens.json '
            f'(cassini-ux brand tokens {tokens["version"]}). Do not edit. */\n'
            ':root {\n' + block('light', '  ') + '}\n'
            '@media (prefers-color-scheme: dark) {\n  :root {\n' + block('dark', '    ') + '  }\n}\n')


def main(argv):
    text = render(json.loads(SOURCE.read_text()))
    if '--write' in argv:
        TARGET.write_text(text)
        return 0
    if TARGET.read_text() != text:
        print(f'{TARGET.relative_to(root)} is stale: run python3 tools/brand-tokens.py --write', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
